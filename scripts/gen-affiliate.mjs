// ONE-TIME migration tool.
// /go/ mappings now live in src/data/affiliateLinks.ts (the source of truth).
// This script read public/_redirects and emitted that file. Do NOT re-run
// unless you intend to regenerate from _redirects (which no longer holds /go/ lines).
import fs from 'fs';
import path from 'path';

const redirectsPath = path.resolve('public/_redirects');
const content = fs.readFileSync(redirectsPath, 'utf8');
const map = {};
for (const line of content.split('\n')) {
  const t = line.trim();
  if (!t || t.startsWith('#')) continue;
  const parts = t.split(/\s+/);
  if (parts.length >= 2 && parts[0].startsWith('/go/')) {
    const slug = parts[0].replace('/go/', '').replace(/\/$/, '');
    if (slug) map[slug] = parts[1];
  }
}
const header = `// Auto-generated by scripts/gen-affiliate.mjs from public/_redirects.
// SOURCE OF TRUTH for /go/<slug> -> destination URL.
// To ADD an affiliate link: add an entry below, then \`npm run build\`.
export const affiliateLinks: Record<string, string> = `;
fs.mkdirSync(path.dirname(path.resolve('src/data/affiliateLinks.ts')), { recursive: true });
fs.writeFileSync(path.resolve('src/data/affiliateLinks.ts'), header + JSON.stringify(map, null, 2) + ';\n');
console.log('Wrote', Object.keys(map).length, 'affiliate links to src/data/affiliateLinks.ts');
